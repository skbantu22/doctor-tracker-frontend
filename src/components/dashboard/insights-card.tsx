"use client";

import { AlertTriangle, CheckCircle2, Info, RefreshCw, Sparkles } from "lucide-react";
import { ApiError } from "@/lib/api";
import { useInsights } from "@/lib/queries";
import type { Insight } from "@/lib/types";

const toneIcon: Record<Insight["tone"], typeof Info> = { positive: CheckCircle2, neutral: Info, attention: AlertTriangle };
const toneLabel: Record<Insight["tone"], string> = { positive: "Healthy signal", neutral: "Observation", attention: "Needs attention" };

/** Optional AI summary of the dashboard. Hidden entirely when the API has no Gemini key configured. */
export function InsightsCard({ months, enabled }: { months: number; enabled: boolean }) {
  const insights = useInsights(months, enabled);
  if (insights.error instanceof ApiError && insights.error.status === 503) return null;

  return (
    <section className="panel insights-panel" aria-labelledby="insights-title" aria-busy={insights.isFetching}>
      <div className="panel-heading">
        <div>
          <span className="panel-kicker insights-kicker"><Sparkles size={12} /> AI INSIGHTS</span>
          <h2 id="insights-title">What stands out in the last {months} months</h2>
        </div>
        <button className="icon-button" onClick={() => insights.refetch()} disabled={insights.isFetching} aria-label="Regenerate insights" title="Regenerate insights">
          <RefreshCw size={15} className={insights.isFetching ? "spin" : undefined} />
        </button>
      </div>

      {insights.isLoading || !enabled ? (
        <div className="insights-grid">{[0, 1, 2].map((index) => <span key={index} className="skeleton-block insight-skeleton" />)}</div>
      ) : insights.isError ? (
        <p className="insights-error">{insights.error.message} <button onClick={() => insights.refetch()}>Try again</button></p>
      ) : (
        <ul className="insights-grid">
          {insights.data?.insights.map((insight) => {
            const Icon = toneIcon[insight.tone] ?? Info;
            return (
              <li key={insight.title} className={`insight insight-${insight.tone}`}>
                <span className="insight-icon" title={toneLabel[insight.tone]}><Icon size={15} aria-hidden /><span className="sr-only">{toneLabel[insight.tone]}</span></span>
                <div><strong>{insight.title}</strong><p>{insight.detail}</p></div>
              </li>
            );
          })}
        </ul>
      )}
      <p className="insights-footnote">Generated by Google Gemini from aggregate counts only, with no patient-level data. Check important figures against the charts.</p>
    </section>
  );
}
